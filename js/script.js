const root = document.documentElement;
const languageToggle = document.getElementById("lang-toggle");
const themeToggle = document.getElementById("theme-toggle");
const menuToggle = document.getElementById("menu-toggle");
const navPanel = document.getElementById("site-nav-links");
const navLinks = [...document.querySelectorAll(".nav-panel a")];
const musicPlayer = document.getElementById("music-player");
const musicToggle = document.getElementById("music-toggle");
const musicDetails = document.getElementById("music-details");
const moonSecret = document.getElementById("moon-secret");
const moonTooltip = document.getElementById("moon-tooltip");
const portraitTrigger = document.getElementById("portrait-trigger");
const portraitLightbox = document.getElementById("portrait-lightbox");
const portraitClose = document.getElementById("portrait-close");

function applyLanguage(language) {
  const dictionary = translations[language];

  document.title = dictionary.page_title;
  document.querySelector('meta[name="description"]').content = dictionary.page_description;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = dictionary[element.dataset.i18nHtml];
    if (value) element.innerHTML = value;
  });

  root.lang = language === "pt" ? "pt-BR" : "en";
  document.querySelector(".lang-current").textContent = language.toUpperCase();
  localStorage.setItem("language", language);
}

function applyTheme(theme) {
  root.dataset.theme = theme;
  localStorage.setItem("theme", theme);
}

const savedLanguage = localStorage.getItem("language") || "pt";
const savedTheme = localStorage.getItem("theme") || "dark";
applyLanguage(savedLanguage);
applyTheme(savedTheme);

languageToggle.addEventListener("click", () => {
  applyLanguage((localStorage.getItem("language") || "pt") === "pt" ? "en" : "pt");
});

themeToggle.addEventListener("click", () => {
  applyTheme((root.dataset.theme || "dark") === "dark" ? "light" : "dark");
});

function setMenu(open) {
  navPanel.classList.toggle("is-open", open);
  menuToggle.classList.toggle("is-open", open);
  menuToggle.setAttribute("aria-expanded", String(open));
}

menuToggle.addEventListener("click", () => setMenu(!navPanel.classList.contains("is-open")));
navLinks.forEach((link) => link.addEventListener("click", () => setMenu(false)));

function setMusicPlayer(open) {
  musicPlayer.classList.toggle("is-open", open);
  musicToggle.setAttribute("aria-expanded", String(open));
  musicDetails.hidden = !open;
}

musicToggle.addEventListener("click", () => setMusicPlayer(!musicPlayer.classList.contains("is-open")));

portraitTrigger.addEventListener("click", () => portraitLightbox.showModal());
portraitClose.addEventListener("click", () => portraitLightbox.close());
portraitLightbox.addEventListener("click", (event) => {
  if (event.target === portraitLightbox) portraitLightbox.close();
});

function setMoonSecret(open) {
  moonSecret.setAttribute("aria-expanded", String(open));
  moonTooltip.classList.toggle("is-visible", open);
}

moonSecret.addEventListener("click", () => setMoonSecret(moonSecret.getAttribute("aria-expanded") !== "true"));

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") setMenu(false);
  if (event.key === "Escape") setMusicPlayer(false);
  if (event.key === "Escape") setMoonSecret(false);
});

document.addEventListener("click", (event) => {
  if (!moonSecret.contains(event.target) && !moonTooltip.contains(event.target)) setMoonSecret(false);
});

const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const revealElements = document.querySelectorAll(".reveal");

if (reducedMotion) {
  revealElements.forEach((element) => element.classList.add("is-visible"));
} else {
  const revealObserver = new IntersectionObserver(
    (entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    },
    { threshold: 0.12 },
  );

  revealElements.forEach((element) => revealObserver.observe(element));
}

const chapters = [...document.querySelectorAll("main section.chapter[id]")];
const activeObserver = new IntersectionObserver(
  (entries) => {
    const visibleEntry = entries.find((entry) => entry.isIntersecting);
    if (!visibleEntry) return;

    navLinks.forEach((link) => {
      link.classList.toggle("active", link.getAttribute("href") === `#${visibleEntry.target.id}`);
    });
  },
  { rootMargin: "-40% 0px -55% 0px", threshold: 0 },
);

chapters.forEach((chapter) => activeObserver.observe(chapter));
